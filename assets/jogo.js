const revealPlayerOutput = document.querySelector('[data-reveal-player]');
const revealButton = document.querySelector('[data-reveal]');
const gameActions = document.querySelector('[data-actions]');
const playerOneInput = document.querySelector('[data-player-one]');
const playerTwoInput = document.querySelector('[data-player-two]');

let selectedLevel = 'quente';
let round = 1;
let deck = [];
let currentIndex = 0;
let playerNames = ['Amor 1', 'Amor 2'];

try {
    const savedNames = JSON.parse(localStorage.getItem('entreNosJogadores'));

    if (Array.isArray(savedNames)) {
        playerOneInput.value = typeof savedNames[0] === 'string' ? savedNames[0] : '';
        playerTwoInput.value = typeof savedNames[1] === 'string' ? savedNames[1] : '';
    }
} catch {
    // O jogo continua normalmente quando o armazenamento não está disponível.
}

function shuffled(items) {
    const result = [...items];

    for (let index = result.length - 1; index > 0; index -= 1) {
        const randomIndex = Math.floor(Math.random() * (index + 1));
        [result[index], result[randomIndex]] = [result[randomIndex], result[index]];
    }

    return result;
}

function showScreen(screen) {
    [intro, board, finish].forEach((section) => { section.hidden = section !== screen; });
}

function renderCard(animate = false) {
    const [type, icon, text] = deck[currentIndex];
    const currentPlayer = playerNames[(round - 1) % 2];
    levelLabel.textContent = `Nível ${selectedLevel}`;
    roundOutput.textContent = round;
    progress.style.width = `${(round / 12) * 100}%`;
    playerOutput.textContent = currentPlayer;
    gatePlayerOutput.textContent = currentPlayer;
    revealPlayerOutput.textContent = currentPlayer;
    typeOutput.textContent = type;
    numberOutput.textContent = String(round).padStart(2, '0');
    iconOutput.textContent = icon;
    challengeOutput.textContent = text;

    if (animate) {
        card.classList.remove('is-changing');
        void card.offsetWidth;
        card.classList.add('is-changing');
    }

    if (!card.hidden) {
        window.setTimeout(() => card.focus({ preventScroll: true }), animate ? 370 : 0);
    }
}

function concealCard() {
    card.hidden = true;
    gameActions.hidden = true;
    privacyGate.hidden = false;
    window.setTimeout(() => revealButton.focus({ preventScroll: true }), 0);
}

function revealCard() {
    privacyGate.hidden = true;
    card.hidden = false;
    gameActions.hidden = false;
    card.focus({ preventScroll: true });
}

function startGame() {
    const enteredNames = [playerOneInput.value.trim(), playerTwoInput.value.trim()];
    playerNames = [enteredNames[0] || 'Amor 1', enteredNames[1] || 'Amor 2'];

    try {
        localStorage.setItem('entreNosJogadores', JSON.stringify(enteredNames));
    } catch {
        // Salvar os nomes é opcional e não impede o início do jogo.
    }

    round = 1;
    currentIndex = 0;
    deck = shuffled(challenges[selectedLevel]);
    showScreen(board);
    renderCard();
    concealCard();
}

function advanceCard() {
    if (round >= 12) {
        showScreen(finish);
        return;
    }

    round += 1;
    currentIndex += 1;
    renderCard();
    concealCard();
}

function passCard() {
    const previousCard = deck[currentIndex];
    currentIndex += 1;

    if (currentIndex >= deck.length) {
        deck = shuffled(challenges[selectedLevel]);

        if (deck[0] === previousCard && deck.length > 1) {
            [deck[0], deck[1]] = [deck[1], deck[0]];
        }

        currentIndex = 0;
    }

    renderCard(true);
}

levelButtons.forEach((button) => {
    button.addEventListener('click', () => {
        selectedLevel = button.dataset.level;
        levelButtons.forEach((option) => option.classList.toggle('is-selected', option === button));
    });
});

document.querySelector('[data-start]').addEventListener('click', startGame);
document.querySelector('[data-next]').addEventListener('click', advanceCard);
document.querySelector('[data-pass]').addEventListener('click', passCard);
document.querySelector('[data-restart]').addEventListener('click', startGame);
document.querySelector('[data-back]').addEventListener('click', () => showScreen(intro));
revealButton.addEventListener('click', revealCard);
